import numpy as np

suppliers = [
    {"name": "Supplier A", "cost": 50, "quality": 90, "delivery": 5, "risk": 10, "capacity": 1000},
    {"name": "Supplier B", "cost": 45, "quality": 85, "delivery": 7, "risk": 15, "capacity": 1200},
    {"name": "Supplier C", "cost": 55, "quality": 95, "delivery": 4, "risk": 8, "capacity": 800},
    {"name": "Supplier D", "cost": 48, "quality": 88, "delivery": 6, "risk": 12, "capacity": 1500},
    {"name": "Supplier E", "cost": 52, "quality": 92, "delivery": 5, "risk": 7, "capacity": 900}
]

DEMAND = 3000

W_COST = 0.40
W_QUALITY = 0.25
W_DELIVERY = 0.20
W_RISK = 0.15

cost = np.array([s["cost"] for s in suppliers], dtype=float)
quality = np.array([s["quality"] for s in suppliers], dtype=float)
delivery = np.array([s["delivery"] for s in suppliers], dtype=float)
risk = np.array([s["risk"] for s in suppliers], dtype=float)
capacity = np.array([s["capacity"] for s in suppliers], dtype=float)

def normalize(x):
    return (x - np.min(x)) / (np.max(x) - np.min(x) + 1e-10)

cost_norm = normalize(cost)
quality_norm = 1 - normalize(quality)
delivery_norm = normalize(delivery)
risk_norm = normalize(risk)

supplier_score = (
    W_COST * cost_norm
    + W_QUALITY * quality_norm
    + W_DELIVERY * delivery_norm
    + W_RISK * risk_norm
)

def fitness(position):
    total_quantity = np.sum(position)
    objective = np.sum(position * supplier_score)
    shortage = max(0, DEMAND - total_quantity)
    penalty = 1000 * shortage
    return objective + penalty

NUM_PARTICLES = 50
MAX_ITERATIONS = 200
INERTIA = 0.7
C1 = 1.5
C2 = 1.5

NUM_SUPPLIERS = len(suppliers)

lower_bound = np.zeros(NUM_SUPPLIERS)
upper_bound = capacity.copy()

positions = np.random.uniform(
    lower_bound,
    upper_bound,
    size=(NUM_PARTICLES, NUM_SUPPLIERS)
)

velocities = np.zeros((NUM_PARTICLES, NUM_SUPPLIERS))

personal_best_positions = positions.copy()

personal_best_scores = np.array([
    fitness(p) for p in positions
])

best_index = np.argmin(personal_best_scores)

global_best_position = personal_best_positions[best_index].copy()
global_best_score = personal_best_scores[best_index]

for iteration in range(MAX_ITERATIONS):

    for i in range(NUM_PARTICLES):

        r1 = np.random.random(NUM_SUPPLIERS)
        r2 = np.random.random(NUM_SUPPLIERS)

        velocities[i] = (
            INERTIA * velocities[i]
            + C1 * r1 * (personal_best_positions[i] - positions[i])
            + C2 * r2 * (global_best_position - positions[i])
        )

        positions[i] = positions[i] + velocities[i]

        positions[i] = np.clip(
            positions[i],
            lower_bound,
            upper_bound
        )

        current_score = fitness(positions[i])

        if current_score < personal_best_scores[i]:

            personal_best_scores[i] = current_score
            personal_best_positions[i] = positions[i].copy()

            if current_score < global_best_score:
                global_best_score = current_score
                global_best_position = positions[i].copy()

solution = global_best_position.copy()

total = np.sum(solution)

if total > DEMAND:
    solution = solution * (DEMAND / total)

total_cost = 0

print("\nOPTIMAL SUPPLIER SELECTION")
print("-" * 40)

for i, quantity in enumerate(solution):

    if quantity > 0.01:

        supplier = suppliers[i]
        supplier_cost = quantity * supplier["cost"]
        total_cost += supplier_cost

        print(
            f"{supplier['name']}: "
            f"{quantity:.2f} units | "
            f"Unit Cost: ${supplier['cost']}"
        )

print("-" * 40)
print(f"Total Quantity: {np.sum(solution):.2f}")
print(f"Required Demand: {DEMAND}")
print(f"Total Procurement Cost: ${total_cost:.2f}")
print(f"Objective Value: {fitness(solution):.4f}")